export const BREEDS: ReadonlyArray<Breed> = RAW.map(([value, label]) => ({
  value,
  label,
}));

// "mix" isn't a single identifiable breed, so it can't be a fair quiz answer.
const NOT_QUIZZABLE = new Set(["mix"]);

export const QUIZ_BREEDS: ReadonlyArray<Breed> = BREEDS.filter(
  (b) => !NOT_QUIZZABLE.has(b.value),
);

const LABELS = new Map(BREEDS.map((b) => [b.value, b.label]));

/** Display text for a breed id, e.g. "bulldog-boston" -> "Boston Bulldog". */
export function breedLabel(value: string): string {
  const label = LABELS.get(value) ?? value;
  return label.replace(/\b\w/g, (c) => c.toUpperCase());
}
